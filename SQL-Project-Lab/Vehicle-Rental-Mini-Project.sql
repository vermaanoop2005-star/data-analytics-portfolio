select  *  from vehicle
where status = 'Available'

#2Display all Cars with their vehicle name, brand and rent per day
select vehicle_name , brand , rent_per_day from vehicle;

#3Display all Bikes whose rent per day is greater than ₹1,000.
select vehicle_type ,rent_per_day  from vehicle 
where vehicle_type in ('Bike') and  rent_per_day > 1000

#4Display customers whose age is between 25 and 40.
select customer_name ,age from vehicle_customer
where age between 25 and 40

#5Display all bookings where the payment status is Pending.
select  * from booking
where payment_status = 'Pending'

#6Display the customer name, vehicle name, start date and end date for every booking.
select c .customer_name  , v.vehicle_type , b. start_date ,b. end_date from booking b
join  vehicle v
on b.vid = v.vid
join vehicle_customer c
on b.cid = c.cid


#7Display customer name, phone number, vehicle name and bill amount for all bookings
select c. customer_name  , c. phone_number  ,v.vehicle_name ,  b.bill_amount  from vehicle_customer c
join  vehicle v
on c.cid = c.cid
join booking b
on b.vid = v.vid


#8 Display all bookings for Cars along with customer details.
select  * from booking b
left join  vehicle v
on v.vid =b.vid
left join vehicle_customer c
on c.cid = b.cid
where v.vehicle_type = 'Car'

#9 Display all customers who have made at least one booking.
select  distinct c. customer_name  from vehicle_customer c
join booking b
on b.cid=c.cid

#10 Display all vehicles that have been booked at least once
select distinct  v.vehicle_name  from vehicle v
join  booking b
on v.vid =b.vid

