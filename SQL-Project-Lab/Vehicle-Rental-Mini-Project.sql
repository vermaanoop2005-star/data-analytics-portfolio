#17 Find the total amount spent by each customer.
#Display customers in descending order of total spending.
select  c.  customer_name   , sum( b.bill_amount) as total_amount from  vehicle_customer c
join booking b
on b.cid = c.cid
group by customer_name 
order by total_amount desc

#18Find the number of bookings for each vehicle.
#Display:Vehicle_NameNumber_of_Bookings

