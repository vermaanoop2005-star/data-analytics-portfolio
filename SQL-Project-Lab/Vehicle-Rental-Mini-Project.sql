create database vehiclerental;
use vehiclerental
create table vehicle (
vid int primary key,
vehicle_name varchar (30),
vehicle_type varchar (15),
brand varchar (10),
model_year int ,
status varchar (20),
fuel_type varchar (10) ,
rent_per_day decimal(10,2) 

);


create table vehicle_customer(
cid int primary key ,
customer_name varchar (10),
phone_number varchar (10) not null,
age int,
licence_number varchar (20),
address varchar (20)
);

create table  booking  (
Bid int primary key ,
cid int  not null ,
vid int not null,
booking_date date  ,
start_date  date ,
end_date  date  ,
payment_status varchar (20),
bill_amount decimal (10,3)


);


